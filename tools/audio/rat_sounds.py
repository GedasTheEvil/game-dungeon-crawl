"""Synthesize the giant rat's pack call (plan giant-rat-pack-call): the rat's bite squeak pitched up a fifth and a half,
played twice in a row with a gap, at full level (the other sounds sit at -3 dB), so it carries over the level.

    python3 tools/audio/rat_sounds.py [out_dir]      (default: media/sounds/monsters/, reads rat_att.wav, writes rat_roar.wav)

The rat's own sounds (rat_{att,die,jump}.wav) are not generated by a script; this one only derives from rat_att.wav.
Output: 16-bit PCM mono 22050 Hz, which SDL_mixer's Mix_LoadWAV reads directly.
"""

import os
import sys
import wave

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from crocodile_sounds import REPO, SR, write  # noqa: E402

PITCH = 1.6  # resampling factor: higher and shorter
GAP_S = 0.06


def read(path):
    with wave.open(path, "rb") as w:
        assert w.getframerate() == SR and w.getnchannels() == 1 and w.getsampwidth() == 2
        return np.frombuffer(w.readframes(w.getnframes()), dtype="<i2") / 32768.0


def squeal(bite):
    shifted = np.interp(np.arange(0, len(bite) - 1, PITCH), np.arange(len(bite)), bite)
    gap = np.zeros(int(GAP_S * SR))
    out = np.concatenate([shifted, gap, shifted * 0.85])
    return out / np.max(np.abs(out)) * 0.98


def main():
    out_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(REPO, "media", "sounds", "monsters")
    write(os.path.join(out_dir, "rat_roar.wav"), squeal(read(os.path.join(out_dir, "rat_att.wav"))))


if __name__ == "__main__":
    main()
