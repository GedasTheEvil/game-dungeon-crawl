namespace {
// Where in a cell the player stands: in front of the ladder, where climbing pulls them anyway.
constexpr float GRIP = LADDER_GRIP_X;
// This close to a closed gate the held key opens it (under GATE_APPROACH, with room for the last walk step), and the
// script waits until it is up.
constexpr float GATE_STOP = GATE_APPROACH - 2 * PLAYER_MOVE_STEP;
constexpr int GATE_WAIT_MS = GATE_OPEN_MS + 200;
// Through an exit or a teleporter: the fade out and back in (Dungeon::updateTravel), with a margin.
const std::string TRAVEL_WAIT = "wait " + std::to_string(2 * GATE_TRAVEL_FADE_MS + 100) + "ms";
static_assert(GATE_STOP > PLAYER_BODY_HALF_WIDTH + PLAYER_MOVE_STEP, "the walk to GATE_STOP must not bump the gate");
constexpr float CLIMB_MARGIN = 0.03f;
constexpr int JUMP_WAIT_MS_PER_STAMINA = 200; // stamina comes back at 5 a second at level 1 (max 100)
constexpr int RUN_UP_EXTRA_MS = 300; // a hold up to a step's face: a little longer than the walk there

// Scenario commands for the path: walks are merged until something else has to happen.
class PathScript {
  public:
	PathScript(const LevelGrid& grid, const std::string& levelPath, float startX) : grid(grid), x(startX) {
		for (int cell = 0; cell < LEVEL_WIDTH * LEVEL_HEIGHT; cell++)
			if (grid.cells[cell].type == Mirror)
				mirrors[cell] = mirrorDir(grid.cells[cell]);
		out = "# Generated by levelcheck --script: plays the path levelcheck found (god mode).\n";
		out += "seed 1\ngod\npeace\nlevel " + levelPath + "\nwait 30\n";
	}

	std::string build(const LevelReport& r) {
		for (size_t i = 1; i < r.path.size(); i++) {
			const CellPos& cur = r.path[i];
			float target = static_cast<float>(cur.col) + GRIP;
			switch (r.pathMoves[i]) {
			case PathMove::Walk:
				if (grid.at(cur.col, cur.row).type == Gate &&
					gateState(grid.at(cur.col, cur.row)) == GateState::Closed) {
					float dir = target > x ? 1.f : -1.f;
					walkTo(static_cast<float>(cur.col) + (dir > 0 ? -GATE_STOP : 1.f + GATE_STOP));
					line("wait " + std::to_string(GATE_WAIT_MS) + "ms");
				}
				waitForTraps(r.path[i - 1], cur);
				waitForGusts(r.path[i - 1], cur);
				climbOntoStep(r, i);
				if (r.pathTakeOffs[i].empty())
					walkTo(target);
				else
					jumps(r.pathTakeOffs[i], target);
				break;
			case PathMove::Crawl: // into a crawl space (plan subcell-checker): down, through it, the key let go (the
								  // player stays down under the low ceiling until there is room to stand)
				climbOntoStep(r, i);
				line("crouch on");
				walkTo(target);
				line("crouch off");
				break;
			case PathMove::Drop:
				if (!r.pathTakeOffs[i].empty()) { // a stair down then up in one cell: the jumps walk off it
					jumps(r.pathTakeOffs[i], target);
					break;
				}
				walkTo(target);
				line("wait 1500ms");
				break;
			case PathMove::Climb:
				flushWalk();
				climb(cur.row > r.path[i - 1].row ? 1 : -1);
				break;
			case PathMove::Step: // onto a quarter step (plan subcell-checker): a jump, the walk on
			case PathMove::SpikedStep: // the same, into ceiling spikes (plan ceiling-spikes)
			case PathMove::Jump:
				jumps(r.pathTakeOffs[i], target);
				break;
			case PathMove::Pull:
				if (const Fixture& lever = grid.at(cur.col, cur.row).fixture; lever.type == Lever)
					leverColours |= 1 << lever.attr;
				flushWalk();
				line("interact");
				line("wait " + std::to_string(GATE_WAIT_MS) + "ms");
				break;
			case PathMove::Turn: // the mirror here turned with the key, the others the beam needs set as the checker
								 // found
				flushWalk();
				for (const MirrorSetting& m : r.pathTurnWays[turns]) {
					if (m.cell == cur.row * LEVEL_WIDTH + cur.col)
						for (; mirrors[m.cell] != m.dir; mirrors[m.cell] = clockwise(mirrors[m.cell]))
							line("interact");
					else {
						line(
							"mirror " + std::to_string(m.cell % LEVEL_WIDTH) + " " +
							std::to_string(m.cell / LEVEL_WIDTH) + " " + std::to_string(static_cast<int>(m.dir))
						);
						mirrors[m.cell] = m.dir;
					}
				}
				turns++;
				line("wait " + std::to_string(GATE_WAIT_MS) + "ms");
				break;
			case PathMove::Teleport:
				line("interact");
				line(TRAVEL_WAIT);
				x = static_cast<float>(cur.col) + TELEPORT_ARRIVAL_X;
				break;
			case PathMove::Start:
				break;
			}
			// The checker counts reaching the boss as killing it; in god mode the script kills it there.
			Tile t = grid.at(cur.col, cur.row);
			if (t.type == MonsterSpawn && isBossMonster(t.attr) && !bossKilled) {
				bossKilled = true;
				line("wait 500ms");
				line("killboss");
				line("wait 1s");
			}
		}
		flushWalk();
		line("dump");
		line("interact");
		line(r.finale ? "wait 5" : TRAVEL_WAIT);
		line(r.finale ? "expect won == 1" : "expect level == 2");
		return out;
	}

  private:
	const LevelGrid& grid;
	float x;
	std::string out;
	float walkDir = 0.f;
	int climbDir = 0;
	int climbRows = 0;
	bool bossKilled = false;
	std::map<int, BeamDir> mirrors; // the way each mirror points by now
	size_t turns = 0; // Turn moves so far
	int leverColours = 0; // bit per colour a pulled lever opened: its gates are up
	std::set<int> gatesOpened; // cells of the key gates the script walked up to

	// The jumps into a path cell and inside it (plan subcell-checker-mismatches), then the walk to target with the walk
	// key held from the last take-off. Each jump: the gates on its arc opened first (a key gate only opens as the
	// player comes up to it), the stamina for it, the run-up to where the checker takes off, facing the jump's way
	// (after a drop the player may face back), then the jump.
	void jumps(const std::vector<PathTakeOff>& takeOffs, float target) {
		for (size_t j = 0; j < takeOffs.size(); j++) {
			const PathTakeOff& t = takeOffs[j];
			const char* way = t.dir > 0 ? "right" : "left";
			openGatesOnArc(t);
			// The checker does not count stamina; the script waits for a jump's worth (out of quicksand,
			// QUICKSAND_JUMP_STAMINA) at the first level's regeneration.
			const bool sand = inQuicksand(grid.at(t.x / SUBCELLS, t.y / SUBCELLS));
			line(
				"wait " +
				std::to_string((sand ? QUICKSAND_JUMP_STAMINA : JUMP_STAMINA_COST) * JUMP_WAIT_MS_PER_STAMINA) + "ms"
			);
			if (t.face == 1) { // the face right ahead: walk up against it
				const float face = static_cast<float>(t.dir > 0 ? t.x + 1 : t.x) * SUBCELL_SIZE;
				const int ms = static_cast<int>(std::fabs(face - x) / WALK_SPEED * 1000.f) + RUN_UP_EXTRA_MS;
				line("hold " + std::string(way) + " " + std::to_string(ms) + "ms");
				x = face - static_cast<float>(t.dir) * SUBCELL_SIZE / 2;
			} else {
				// A step farther on: from the take-off sub-cell's middle, the reach the checker counts from (a jump
				// over a gap keeps the cell's grip, as the cells' walk left the player there).
				if (t.face > 1)
					walkTo((static_cast<float>(t.x) + 0.5f) * SUBCELL_SIZE);
				line("hold " + std::string(way) + " 1");
			}
			line("jump");
			if (j + 1 < takeOffs.size()) { // the walk key held through the air and on up to the next step
				line("hold " + std::string(way) + " " + std::to_string(Jump::ARC.ms() + RUN_UP_EXTRA_MS) + "ms");
				x = (static_cast<float>(t.landX) + 0.5f) * SUBCELL_SIZE;
			}
		}
		// Onto a shaped cell: the walk ends on the sub-cell landed on, not the cell's grip (a stair goes back down
		// there, the next step's face may be on the way).
		if (!takeOffs.empty()) {
			const PathTakeOff& last = takeOffs.back();
			if (grid.at(last.landX / SUBCELLS, last.y / SUBCELLS).shape != 0)
				target = (static_cast<float>(last.landX) + 0.5f) * SUBCELL_SIZE;
		}
		walkTo(target);
		flushWalk();
		line("wait 500ms");
	}

	// The closed gates between the take-off and the landing: walked up to with the key, so they open.
	void openGatesOnArc(const PathTakeOff& t) {
		const int row = t.y / SUBCELLS;
		for (int col = t.x / SUBCELLS + t.dir; col != t.landX / SUBCELLS + t.dir; col += t.dir) {
			const Tile gate = grid.at(col, row);
			const int cell = row * LEVEL_WIDTH + col;
			if (gate.type != Gate || gateState(gate) != GateState::Closed || (leverColours & (1 << gate.attr)) != 0 ||
				gatesOpened.count(cell) != 0)
				continue;
			gatesOpened.insert(cell);
			walkTo(static_cast<float>(col) + (t.dir > 0 ? -GATE_STOP : 1.f + GATE_STOP));
			line("wait " + std::to_string(GATE_WAIT_MS) + "ms");
		}
	}

	// Off a ladder onto a step beside it (plan subcell-checker-mismatches): the step's face stops the player at the
	// ladder's foot, so up the ladder to the step's height first.
	void climbOntoStep(const LevelReport& r, size_t i) {
		const CellPos& prev = r.path[i - 1];
		if (r.pathRise[i] <= 0 || grid.at(prev.col, prev.row).type != Ladder)
			return;
		char buf[64];
		snprintf(
			buf,
			sizeof(buf),
			"walk up %.2f",
			static_cast<double>(static_cast<float>(r.pathRise[i]) * SUBCELL_SIZE + CLIMB_MARGIN + CLIMB_MARGIN)
		);
		line(buf);
	}

	// Stepping from prev into a run of sand gusts against the wind (plan sandstorm-halls): wait in prev for the calm
	// that lets the player cross the whole run.
	void waitForGusts(const CellPos& prev, const CellPos& cur) {
		auto gust = [this, &cur](int col) { return grid.at(col, cur.row).fixture.type == SandGust; };
		if (prev.row != cur.row || gust(prev.col) || !gust(cur.col))
			return;
		const int step = cur.col - prev.col;
		if (gustDir(grid.at(cur.col, cur.row).fixture) != -step)
			return; // with the wind: it only helps
		int left = cur.col;
		while (gust(left - 1))
			left--;
		int right = cur.col;
		while (gust(right + 1))
			right++;
		flushWalk();
		line(
			"waittraps " + std::to_string(left) + " " + std::to_string(right - left + 1) +
			(step > 0 ? " right" : " left")
		);
	}

	// Stepping from prev into a run of rhythm traps with wall spikes in it (out, they block): wait in prev until the
	// whole run can be walked through.
	void waitForTraps(const CellPos& prev, const CellPos& cur) {
		auto trap = [this, &cur](int col) { return isRhythmTrap(grid.at(col, cur.row).fixture.type); };
		if (prev.row != cur.row || trap(prev.col) || !trap(cur.col))
			return;
		int left = cur.col;
		while (trap(left - 1))
			left--;
		int right = cur.col;
		while (trap(right + 1))
			right++;
		bool spikes = false;
		for (int c = left; c <= right; c++)
			spikes = spikes || grid.at(c, cur.row).fixture.type == WallSpikes;
		if (!spikes)
			return;
		flushWalk();
		line(
			"waittraps " + std::to_string(left) + " " + std::to_string(right - left + 1) +
			(cur.col > prev.col ? " right" : " left")
		);
	}

	void line(const std::string& text) {
		flushWalk();
		flushClimb();
		out += text + "\n";
	}

	void walkTo(float target) {
		flushClimb();
		float dir = target > x ? 1.f : -1.f;
		if (std::fabs(target - x) < 0.001f)
			return;
		if (walkDir != 0.f && dir != walkDir)
			flushWalk();
		walkDir = dir;
		x = target;
	}

	void flushWalk() {
		if (walkDir == 0.f)
			return;
		// To the absolute target: relative walks would add up the small differences between the path's cells and
		// where the game's physics puts the player.
		char buf[64];
		snprintf(buf, sizeof(buf), "walk to %.3f\n", static_cast<double>(x));
		out += buf;
		walkDir = 0.f;
	}

	void climb(int dir) {
		if (climbDir != 0 && dir != climbDir)
			flushClimb();
		climbDir = dir;
		climbRows++;
	}

	void flushClimb() {
		if (climbDir == 0)
			return;
		// Up a little past the row, down a little short of it: the player must end inside the target row, and
		// walking down onto the exact row edge would round into the cell below.
		char buf[64];
		snprintf(
			buf,
			sizeof(buf),
			"walk %s %.2f\n",
			climbDir > 0 ? "up" : "down",
			static_cast<double>(climbRows) + (climbDir > 0 ? CLIMB_MARGIN : -CLIMB_MARGIN)
		);
		out += buf;
		climbDir = 0;
		climbRows = 0;
	}
};

} // namespace

std::string pathScript(const LevelGrid& grid, const LevelReport& report, const std::string& levelPath, float startX) {
	return PathScript(grid, levelPath, startX).build(report);
}
